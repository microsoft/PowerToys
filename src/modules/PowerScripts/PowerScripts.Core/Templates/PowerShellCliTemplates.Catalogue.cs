using System.Text;
using PowerScripts.Core.Templates.CliModules;

namespace PowerScripts.Core.Templates;

public static partial class PowerShellCliTemplates
{
    internal static IReadOnlyList<PowerShellCliModule> Modules { get; } =
        typeof(PowerShellCliModule).Assembly.GetTypes()
            .Where(type => !type.IsAbstract && typeof(PowerShellCliModule).IsAssignableFrom(type))
            .Select(type => (PowerShellCliModule)Activator.CreateInstance(type, nonPublic: true)!)
            .OrderBy(module => module.Order).ThenBy(module => module.Id, StringComparer.Ordinal).ToArray();

    public static IReadOnlyList<PowerShellCliTemplate> All { get; } = CreateCatalogue(Modules);

    private static IReadOnlyList<PowerShellCliTemplate> LegacyCatalogue { get; } = CreateLegacyCatalogue();

    internal static IReadOnlyList<PowerShellCliTemplate> CreateCatalogue(IEnumerable<PowerShellCliModule> modules)
    {
        var moduleIds = new HashSet<string>(StringComparer.Ordinal);
        var recipeIds = new HashSet<string>(StringComparer.Ordinal);
        var recipes = new List<PowerShellCliTemplate>();
        foreach (var module in modules)
        {
            if (string.IsNullOrWhiteSpace(module.Id) || !moduleIds.Add(module.Id) ||
                string.IsNullOrWhiteSpace(module.Name) || string.IsNullOrWhiteSpace(module.Executable))
            {
                throw new InvalidOperationException($"Invalid or duplicate CLI module: '{module.Id}'.");
            }

            var definitions = module.CreateRecipes();
            if (definitions.Count == 0)
            {
                throw new InvalidOperationException($"CLI module '{module.Id}' requires recipes.");
            }

            foreach (var recipe in definitions)
            {
                if (!recipeIds.Add(recipe.Id) || !recipe.Id.StartsWith(module.Id + "-", StringComparison.Ordinal) ||
                    string.IsNullOrWhiteSpace(recipe.Name) || string.IsNullOrWhiteSpace(recipe.Description) ||
                    string.IsNullOrWhiteSpace(recipe.CommandSynopsis) ||
                    recipe.Input is not ("none" or "text" or "files") || recipe.Output is not ("none" or "text" or "files") ||
                    (recipe.SupportsFileBatch && recipe.Input != "files") ||
                    (recipe.Output is "none" or "files" && string.IsNullOrWhiteSpace(recipe.OutputScript)))
                {
                    throw new InvalidOperationException($"Invalid or duplicate CLI recipe: '{recipe.Id}'.");
                }

                recipes.Add(recipe with { ModuleId = module.Id, Group = module.Name, IconName = module.IconName });
            }
        }

        return recipes.AsReadOnly();
    }

    public static string CreateScenarioMatrix()
    {
        var text = new StringBuilder();
        text.Append("<!-- Generated by PowerScripts.Host template cli-matrix. Do not edit this table. -->\n\n");
        text.Append("| Module | Creation recipe | Native commands/options | Default input | Output | Functionality and restrictions |\n");
        text.Append("| --- | --- | --- | --- | --- | --- |\n");
        foreach (var recipe in All)
        {
            var input = recipe.Input == "files" ? recipe.SupportsFileBatch ? "files (batch)" : "files (one)" : recipe.Input;
            text.Append("| ").Append(Cell(recipe.Group))
                .Append(" | `").Append(recipe.Id).Append('`')
                .Append(" | ").Append(Cell(recipe.CommandSynopsis))
                .Append(" | ").Append(input)
                .Append(" | ").Append(recipe.Output)
                .Append(" | ").Append(Cell(recipe.Description)).Append(" |\n");
        }

        return text.ToString();
    }

    private static string Cell(string text) => text.Replace("&", "&amp;", StringComparison.Ordinal)
        .Replace("|", "&#124;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal)
        .Replace(">", "&gt;", StringComparison.Ordinal).Replace("\r", string.Empty, StringComparison.Ordinal)
        .Replace("\n", "<br>", StringComparison.Ordinal);

    private static IReadOnlyList<PowerShellCliTemplate> CreateLegacyCatalogue() =>
        CreateDefinitions().Select(recipe =>
        {
            var module = Modules.OrderByDescending(module => module.Id.Length).First(module =>
                recipe.Id == module.Id || recipe.Id.StartsWith(module.Id + "-", StringComparison.Ordinal));
            return recipe with
            {
                ModuleId = module.Id,
                Group = module.Name,
                IconName = module.IconName,
                SupportsFileBatch = recipe.Id == "image-resizer",
                WritesState = recipe.Id is "advanced-paste-transform" or "fancyzones" or "workspaces" or "light-switch" or "settings-module-state",
                UsesNetwork = recipe.Id == "advanced-paste-transform",
            };
        }).ToArray();
}
